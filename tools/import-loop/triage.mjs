#!/usr/bin/env node
// Loop step: turn one pass's blocker findings into tracked issues and Cook work.
//
// Usage: node triage.mjs --findings <findings.json> --source <kept source dir>
//          --blocks-engine <clone> --work <dir> --iteration N [--prev <sig,sig>] [--prev-merged N] [--dry-run 1]
//
// For each blocker finding, in order:
//   1. An issue whose body carries the signature tracks it (open), or records
//      that a closed fix did not hold (closed).
//   2. Otherwise, when predicates/<check>.mjs exists, the source page is
//      reduced with it, the reduced page is re-checked, and one issue is filed
//      in the owning repository with the reduced page and the predicate.
//   3. Otherwise the finding stays untracked: it needs a predicate first.
// Tracked open issues become Cook items unless an open pull request's head
// already clears every acceptance cell; a refuted pull request is re-cooked on
// its branch with the cells it still fails. Every
// tracked finding with a predicate lists its acceptance cells: the full
// captured page of each route/width it was seen in, which confirm.mjs re-checks
// on each fix's head.
// The pass continues the chain only when it can make progress: something is
// tracked, and the blocker set changed or the previous pass merged a fix.

import { execFileSync, spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { chromium } from 'playwright';
import { args, cellsAtHead, gh, linkedPullRequests, predicateEnv, predicateExit, reimportSite, scopeKeys, collateralAtHead } from './lib.mjs';

const here = path.dirname(new URL(import.meta.url).pathname);
for (const required of ['findings', 'source', 'work', 'iteration', 'blocks-engine']) if (!args[required]) throw new Error(`triage_argument_missing: --${required}`);
const repos = JSON.parse(fs.readFileSync(path.join(here, 'repos.json'), 'utf8'));
const result = JSON.parse(fs.readFileSync(args.findings, 'utf8'));
const blockers = result.findings.filter((f) => f.severity === 'blocker');
const transformer = path.join(args['blocks-engine'], 'php-transformer');
const reducer = path.join(here, '..', 'reduce-finding.mjs');
const disclosure = 'AI disclosure: filed by the static-site import findings loop (Homeboy workflow on the Lab). The finding, reduction, and body are generated by deterministic scripts; Claude (Anthropic) wrote those scripts with Chris Huber.';
fs.mkdirSync(args.work, { recursive: true });
// One bare WordPress per runs directory serves every pass's contracts and
// re-imports.
const BARE_WP = args['bare-wp'] || path.join(path.dirname(path.resolve(args.work)), 'bare-wp');
// Acceptance re-imports the capture through the importer release Studio
// installs; confirm.mjs and every Cook gate reuse the same capture and zip.
const reimport = { capture: path.join(args.source, new URL(result.url).hostname), ssi_zip: path.join(args.work, 'static-site-importer.zip'), bare_wp: BARE_WP };
// Reproduce against Blocks Engine trunk, so a defect fixed since the last
// release is not filed again.
execFileSync('git', ['-C', path.dirname(transformer), 'fetch', '-q', 'origin', 'trunk']);
execFileSync('git', ['-C', path.dirname(transformer), 'checkout', '-q', '--detach', 'FETCH_HEAD']);

const log = (...parts) => console.error('[triage]', ...parts);

function existingIssue(finding) {
  const hits = JSON.parse(gh('search', 'issues', finding.signature, '--owner', 'Automattic', '--json', 'url,state,number,repository', '-L', '20'));
  return hits.find((h) => h.state === 'open') || hits[0] || null;
}

// One standalone HTML file per captured route, stylesheets inlined.
const pages = new Map();
function routePage(route) {
  if (!pages.has(route)) {
    const website = path.join(args.source, new URL(result.url).hostname, 'website');
    const file = path.join(args.work, 'pages', `${route.replace(/[^a-z0-9]+/gi, '-').replace(/^-|-$/g, '') || 'home'}.html`);
    fs.mkdirSync(path.dirname(file), { recursive: true });
    execFileSync('node', [path.join(here, 'inline.mjs'), path.join(website, route.replace(/^\//, ''), 'index.html'), file], { stdio: 'ignore' });
    pages.set(route, file);
  }
  return pages.get(route);
}
const predicatePath = (check) => path.join(here, 'predicates', `${check}.mjs`);
// The recorded route/width cells a fix must clear, on the full captured page.
// Where the predicate runs the owning repository's code, a cell counts only if
// it reproduces on the whole import at trunk: a cell trunk already clears
// cannot tell a fix apart.
let trunkSite = null;
function acceptanceCells(finding) {
  if (!fs.existsSync(predicatePath(finding.check))) return [];
  const cells = finding.occurrences.filter((o) => o.route).map((o) => ({ route: o.route, width: o.width, evidence: o.evidence, page: routePage(o.route) }));
  if (!repos[finding.owner_repo]?.predicate_root) return cells;
  if (!trunkSite) {
    if (!fs.existsSync(reimport.ssi_zip)) gh('release', 'download', '-R', repos['static-site-importer'].github, '-p', 'static-site-importer.zip', '-O', reimport.ssi_zip);
    trunkSite = reimportSite(transformer, reimport, path.join(args.work, 'trunk-site'));
  }
  return cells.filter((cell) => predicateExit(predicatePath(finding.check), transformer, cell.page, { ...predicateEnv(finding.subject, cell, result.site), PREDICATE_SITE_URL: trunkSite }) === 0);
}

const git = (dir, ...command) => execFileSync('git', ['-C', dir, ...command], { encoding: 'utf8' }).trim();
function reduceAndFile(finding) {
  const predicate = predicatePath(finding.check);
  if (!fs.existsSync(predicate)) return { status: 'untracked', reason: `no predicate for ${finding.check}` };
  const repo = repos[finding.owner_repo];
  if (!repo) return { status: 'untracked', reason: `no repository config for ${finding.owner_repo}` };
  const dir = path.join(args.work, finding.signature);
  fs.mkdirSync(dir, { recursive: true });
  const occurrence = finding.occurrences.find((o) => o.route) || finding.occurrences[0];
  const page = routePage(occurrence.route || '/');
  const env = predicateEnv(finding.subject, occurrence, result.site);
  if (predicateExit(predicate, transformer, page, env) !== 0) return { status: 'untracked', reason: 'predicate does not reproduce on the captured page' };
  log(`reducing ${finding.signature} (${finding.check}) from ${fs.statSync(page).size} bytes`);
  const run = spawnSync('node', [reducer, '--input', page, '--output', path.join(dir, 'out'), '--predicate', `node ${predicate} ${transformer} {candidate}`, '--stage', finding.stage, '--name', finding.signature, '--max-calls', '1500', '--timeout-ms', String(2 * 3600 * 1000)], { encoding: 'utf8', maxBuffer: 64 << 20, env });
  const reduced = path.join(dir, 'out', 'source.html');
  if (run.status !== 0 || !fs.existsSync(reduced) || predicateExit(predicate, transformer, reduced, env) !== 0) return { status: 'untracked', reason: `reduction failed: ${(run.stderr || '').slice(-300)}` };
  const html = fs.readFileSync(reduced, 'utf8');
  const reduction = JSON.parse(fs.readFileSync(path.join(dir, 'out', 'reduction.json'), 'utf8'));
  const body = [
    `## Finding`,
    '',
    `\`${finding.stage}/${finding.check}\` on \`${finding.subject}\`, seen in ${finding.occurrences.length} route/width cell(s) of an imported site:`,
    '',
    '| route | width | evidence |', '| --- | --- | --- |',
    ...finding.occurrences.map((o) => `| \`${o.route ?? '-'}\` | ${o.width ?? '-'} | \`${JSON.stringify(o.evidence).slice(0, 200)}\` |`),
    '',
    `## Reduced page (${Buffer.byteLength(html)} bytes)`,
    '',
    `Reduced from ${reduction.counts_before?.bytes ?? '?'} bytes in ${reduction.predicate_calls ?? '?'} predicate calls.`,
    '',
    '```html', html.trim(), '```',
    '',
    '## Reproduce',
    '',
    `The predicate exits 0 while the defect reproduces (checked against \`blocks-engine\` trunk \`${git(path.dirname(transformer), 'rev-parse', '--short', 'HEAD')}\`). Run it from a \`static-site-importer\` checkout at \`${git(here, 'rev-parse', '--short', 'HEAD')}\`, with the reduced page saved as \`reduced.html\`:`,
    '',
    '```sh',
    [
      `PREDICATE_TARGET='${env.PREDICATE_TARGET}'`,
      `WORDPRESS_PATH=<wordpress with static-site-importer active> WP_CLI='studio wp'`,
      `node tools/import-loop/predicates/${finding.check}.mjs <blocks-engine>/php-transformer reduced.html`,
    ].join(' \\\n  '),
    '```',
    '',
    `<details><summary>predicates/${finding.check}.mjs</summary>`, '',
    '```js', fs.readFileSync(predicate, 'utf8').trim(), '```', '</details>',
    '',
    `Loop signature: \`${finding.signature}\``,
    '',
    '---',
    disclosure,
  ].join('\n');
  const title = `${finding.check.replace(/_/g, ' ')}: ${finding.subject}`.slice(0, 120);
  fs.writeFileSync(path.join(dir, 'issue.md'), body);
  if (args['dry-run']) return { status: 'untracked', reason: `dry run: would file "${title}" in ${repo.github}`, reduced };
  const url = gh('issue', 'create', '-R', repo.github, '--title', title, '--body-file', path.join(dir, 'issue.md')).trim();
  log(`filed ${url}`);
  return { status: 'tracked', issue_url: url, number: Number(url.split('/').pop()), filed: true, reduced: reduced };
}

const tracked = [];
const untracked = [];
for (const finding of blockers) {
  const issue = existingIssue(finding);
  let entry;
  if (issue?.state === 'open') entry = { status: 'tracked', issue_url: issue.url, number: issue.number, filed: false };
  else if (issue) entry = { status: 'untracked', reason: `fix did not hold: ${issue.url} is closed and the finding still reproduces` };
  else entry = reduceAndFile(finding);
  const record = { signature: finding.signature, check: finding.check, repo: finding.owner_repo, subject: finding.subject, ...entry };
  if (record.status === 'tracked') {
    record.cells = acceptanceCells(finding);
    // The import shows the defect but the predicate cannot: a fix gated on it
    // would pass vacuously, so the finding waits for a faithful predicate.
    if (!record.cells.length && fs.existsSync(predicatePath(finding.check)) && repos[finding.owner_repo]?.predicate_root) {
      Object.assign(record, { status: 'untracked', reason: `predicate gap: the import shows ${finding.check} but the predicate does not reproduce it at trunk on any cell` });
    }
  }
  (record.status === 'tracked' ? tracked : untracked).push(record);
}

// Cook promotes only when the repository's own checks pass and, where the
// predicates run this repository's code, the defect is gone from every
// acceptance cell. The gate runs from the root of Cook's worktree; its
// machine-local path reaches Cook as gate environment, not in the command.

function acceptanceGate(item, repo) {
  const gate = path.join(args.work, `${item.signature}.accept.sh`);
  const checked = repo.predicate_root && item.cells.length;
  // Contracts CI runs that the repository's verify command does not.
  const contracts = repo.contracts ? path.join(here, repo.contracts) : null;
  if (contracts) execFileSync('bash', [path.join(here, 'gates/bare-wp.sh'), BARE_WP], { stdio: ['ignore', 'ignore', 'inherit'] });
  fs.writeFileSync(gate, [
    '#!/usr/bin/env bash',
    // Gates run under a private HOME: pin the browsers this HOME installed.
    `export PLAYWRIGHT_BROWSERS_PATH='${process.env.PLAYWRIGHT_BROWSERS_PATH || chromium.executablePath().replace(/(ms-playwright).*$/, '$1')}'`,
    ...(contracts ? [`BARE_WP='${BARE_WP}' bash '${contracts}' || exit 1`] : []),
    checked
      ? `# Acceptance for ${item.issue_url}: the ${item.check} predicate exits 1 (defect gone) on every recorded cell.`
      : `# ${item.issue_url}: the predicates do not run ${item.repo} code; the next pass's import checks this fix.`,
    ...(checked ? [
      `root="$PWD/${repo.predicate_root}"; failed=0; site=$(mktemp -d); base=$(mktemp -d)`,
      `trap 'for d in "$site" "$base/site"; do kill $(cat "$d/.server.pid" 2>/dev/null) 2>/dev/null; done; rm -rf "$site" "$base"' EXIT`,
      `url=$(SSI_ZIP='${reimport.ssi_zip}' BARE_WP='${BARE_WP}' bash '${path.join(here, 'gates/reimport.sh')}' "$root" '${reimport.capture}' "$site") || exit 1; url=$(tail -n1 <<<"$url")`,
    ] : []),
    ...(checked ? item.cells : []).map((cell) => {
      const env = predicateEnv(item.subject, cell, result.site);
      return `PREDICATE_SITE_URL="$url" PREDICATE_TARGET='${env.PREDICATE_TARGET}' WORDPRESS_PATH='${env.WORDPRESS_PATH}' WP_CLI='${env.WP_CLI}' node '${predicatePath(item.check)}' "$root" '${cell.page}'; code=$?; echo "${cell.route}@${cell.width}: exit $code"; [ "$code" = 1 ] || failed=1`;
    }),
    // Scope: nothing outside the finding's elements may change against the
    // import of this change's merge base with trunk.
    ...(checked ? [
      `git fetch -q origin trunk && git archive "$(git merge-base HEAD FETCH_HEAD)" '${repo.predicate_root}' | tar -x -C "$base" || exit 1`,
      `burl=$(SSI_ZIP='${reimport.ssi_zip}' BARE_WP='${BARE_WP}' bash '${path.join(here, 'gates/reimport.sh')}' "$base/${repo.predicate_root}" '${reimport.capture}' "$base/site") || exit 1; burl=$(tail -n1 <<<"$burl")`,
      `node '${path.join(here, 'gates/collateral.mjs')}' "$burl" "$url" '${scopeKeys(item).replace(/'/g, "'\\''")}' '${result.routes.join(',')}'; code=$?; echo "collateral: exit $code"; [ "$code" = 0 ] || failed=1`,
    ] : []),
    checked ? 'exit $failed' : 'exit 0',
  ].join('\n') + '\n');
  // Prompts stay free of machine-local paths: the agent receives the gate as
  // declared provider evidence, the verify command through gate environment.
  return { verify: `(${repo.verify}) && bash "$ACCEPT_GATE"`, gate_env: `ACCEPT_GATE=${gate}`, provider_evidence: JSON.stringify({ id: 'acceptance-gate', source: gate }) };
}

const cook_items = [];
for (const item of tracked) {
  const repo = repos[item.repo];
  const pr = linkedPullRequests(item.issue_url)[0];
  item.open_pr = pr?.url || null;
  const checkable = repo?.predicate_root && item.cells.length;
  const at = { clone: args['blocks-engine'], root: repo?.predicate_root, work: args.work, reimport, site: result.site, routes: result.routes };
  const refuted = pr && checkable ? cellsAtHead(item, pr, at).filter((cell) => cell.exit !== 1) : [];
  const collateral = pr && checkable && !refuted.length ? collateralAtHead(item, pr, at) : { exit: 0 };
  if (refuted.length || collateral.exit) item.refuted = { pr: pr.url, head: pr.headRefOid, cells: refuted, ...(collateral.exit ? { collateral: collateral.report } : {}) };
  // One issue can hold several signatures (one root cause, several subjects): cook it once.
  if ((!pr || item.refuted) && repo && !cook_items.some((cook) => cook.issue_url === item.issue_url)) {
    const prompt = path.join(args.work, `${item.signature}.prompt.md`);
    const gate = acceptanceGate(item, repo);
    fs.writeFileSync(prompt, [
      `Fix ${item.issue_url}.`,
      '',
      `The static-site import loop found \`${item.check}\` on \`${item.subject}\`. The issue holds the reduced page, the evidence, and a predicate that exits 0 while the defect reproduces. Read its comments too (\`gh issue view ${item.issue_url} --comments\`): they carry diagnosis, clarified acceptance, and what earlier attempts tried. Where a comment's diagnosis of the whole site differs from the reduced page, the whole site is authoritative.`,
      ...(refuted.length ? [
        '',
        `${pr.url} (head \`${pr.headRefOid.slice(0, 8)}\`) does not fix it: on a whole re-import of the capture with that head, the predicate still exits 0 on ${refuted.map((c) => `\`${c.route}@${c.width}\``).join(', ')}. Continue on its branch.`,
      ] : []),
      ...(collateral.exit ? [
        '',
        `${pr.url} (head \`${pr.headRefOid.slice(0, 8)}\`) clears the defect but restyles elements outside it on the whole import. Continue on its branch and confine the change to the defect:`,
        ...collateral.report.map((line) => `    ${line.slice(0, 400)}`),
      ] : []),
      '',
      'Done looks like:',
      '- The root cause is fixed in the owning code path, not special-cased for the reduced page.',
      ...(checkable ? [
        '- The defect is gone from every cell below on a whole import of the captured site with your change. The acceptance gate checks exactly that, and Cook runs it before your change can be published. It is attached as provider evidence `acceptance-gate`: run it with bash from your worktree root. It re-imports the capture through the Static Site Importer release with your transformer, serves it, and runs the predicate on each cell (exit 1 per cell means fixed).',
        `- Nothing outside the finding's elements (\`${scopeKeys(item)}\`) changes style on any route or width: the gate re-imports this change's merge base with trunk the same way and compares every element's computed style (\`collateral.mjs\`).`,
        '- Its `reimport.sh` line also runs on its own and prints the imported site\'s URL, for inspecting the import. The site-wide import plans shared template parts and route styles together, which the reduced page alone does not show.',
        '',
        ...item.cells.map((cell) => `  - \`${cell.route}\` at ${cell.width}px: \`${JSON.stringify(cell.evidence).slice(0, 200)}\``),
      ] : ['- The issue\'s predicate exits non-zero on the reduced page with your change.']),
      '- One focused regression test that fails before the fix and passes after, through the public interface.',
    ].join('\n'));
    cook_items.push({ signature: item.signature, repo: item.repo, issue_url: item.issue_url, prompt: `@${prompt}`, ...gate });
  }
}

const signatures = blockers.map((f) => f.signature).sort().join(',');
const stalled = Number(args.iteration) > 1 && signatures === (args.prev || '') && Number(args['prev-merged'] || 0) === 0;
const output = {
  iteration: Number(args.iteration),
  site: result.site,
  reimport,
  routes: result.routes,
  blocker_count: blockers.length,
  signatures,
  tracked,
  untracked,
  tracked_count: tracked.length,
  cook_items,
  cook_count: cook_items.length,
  stalled,
  ...(blockers.length && tracked.length && !stalled ? { continue: true, next_iteration: Number(args.iteration) + 1 } : {}),
};
fs.writeFileSync(path.join(args.work, 'triage.json'), JSON.stringify(output, null, 2));
fs.writeFileSync(process.env.HOMEBOY_STEP_OUTPUT || '/dev/stdout', JSON.stringify(output));
log(`blockers=${blockers.length} tracked=${tracked.length} untracked=${untracked.length} cook=${cook_items.length} stalled=${stalled}`);
