	/**
	 * Build the finding packet artifact set for repair-loop routing.
	 *
	 * @param array<string,mixed>|Static_Site_Importer_Import_Report $report Full import report.
	 * @return array<string,mixed>
	 */
	public static function finding_packets( array|Static_Site_Importer_Import_Report $report ): array {
		$diagnostics = isset( $report['diagnostics'] ) && is_array( $report['diagnostics'] ) ? $report['diagnostics'] : array();
		$packets     = array();

		foreach ( $diagnostics as $diagnostic ) {
			if ( ! is_array( $diagnostic ) || ! self::diagnostic_is_finding_packet_candidate( $diagnostic ) ) {
				continue;
			}

			$packets[] = self::finding_packet_from_diagnostic( $diagnostic, $report );
		}

		return array(
			'schema'        => 'blocks-engine/finding-packets/v1',
			'artifact_type' => 'FindingPacketSet',
			'version'       => 1,
			'status'        => empty( $packets ) ? 'clean' : 'reported',
			'count'         => count( $packets ),
			'packets'       => $packets,
		);
	}

	/**
	 * Detect page routes that materialize without any author stylesheet asset
	 * while their source document demonstrably ships author styles.
	 *
	 * The importer is the only layer that sees both the canonical plan's
	 * asset-to-route scopes and the source artifact, so it owns reporting the
	 * "page ships without its styles while the import reports clean" failure
	 * class (Automattic/blocks-engine#1241) regardless of which upstream stage
	 * regresses next. A page counts as covered when any non-engine stylesheet
	 * asset (coalesced `stylesheet-bundle-*`, uncoalesced `source-author-*`, or
	 * a copied author CSS file) is scoped to its route or declared global;
	 * `engine-support` and `editor-static-state` assets are engine-generated
	 * and never satisfy author coverage. Source evidence requires a non-empty
	 * inline `<style>` payload or a linked stylesheet that resolves to a
	 * non-empty artifact-local CSS file, so a warning always means author CSS
	 * the pipeline had in hand was dropped.
	 *
	 * @param array<string,mixed> $plan     Canonical WordPress site plan.
	 * @param array<string,mixed> $artifact Source website artifact.
	 * @return array<int,array<string,mixed>> Warning diagnostics, one per uncovered route.
	 */
	public static function missing_author_stylesheet_diagnostics( array $plan, array $artifact ): array {
		$pages = isset( $plan['pages'] ) && is_array( $plan['pages'] ) ? $plan['pages'] : array();
		if ( array() === $pages ) {
			return array();
		}

		$coverage = self::author_stylesheet_scope_coverage( isset( $plan['assets'] ) && is_array( $plan['assets'] ) ? $plan['assets'] : array() );
		$files    = self::artifact_file_contents( $artifact );

		$diagnostics = array();
		foreach ( $pages as $page ) {
			if ( ! is_array( $page ) || ! is_scalar( $page['source_path'] ?? null ) ) {
				continue;
			}
			$source_path  = (string) $page['source_path'];
			$scoped_count = (int) ( $coverage['by_source_path'][ $source_path ] ?? 0 );
			if ( $scoped_count > 0 || $coverage['global_count'] > 0 ) {
				continue;
			}
			$html = $files[ $source_path ] ?? '';
			if ( '' === $html ) {
				continue; // Without source content there is no proof author styles were lost.
			}
			$inline_count = self::nonempty_inline_style_count( $html );
			$linked_count = self::linked_local_stylesheet_count( $html, $source_path, $files );
			if ( 0 === $inline_count && 0 === $linked_count ) {
				continue;
			}
			$route         = (string) ( $page['route']['path'] ?? '' );
			$route_path    = trim( $route, '/' );
			$diagnostics[] = array(
				'type'        => Static_Site_Importer_Report_Diagnostics::PAGE_WITHOUT_AUTHOR_STYLES_TYPE,
				'code'        => Static_Site_Importer_Report_Diagnostics::PAGE_WITHOUT_AUTHOR_STYLES_TYPE,
				'severity'    => 'warning',
				'source'      => $source_path,
				'source_path' => $source_path,
				'route_path'  => $route_path,
				'front_page'  => '/' === $route,
				'message'     => sprintf(
					'Page %1$s (route "/%2$s") materialized without any author stylesheet asset scoped to its route while its source document contains author styles (%3$d inline style block(s), %4$d linked local stylesheet(s)). The imported page will render without its source styling.',
					$source_path,
					$route_path,
					$inline_count,
					$linked_count
				),
				'reason_code' => 'no_author_scoped_stylesheet_assets',
				'stage'       => 'materialization',
				'loss_class'  => Static_Site_Importer_Diagnostic_Loss_Classes::IMPORTER_MATERIALIZATION_BUG,
				'context'     => array(
					'source_path'                          => $source_path,
					'route_path'                           => $route_path,
					'author_scoped_stylesheet_asset_count' => $scoped_count,
					'global_author_stylesheet_asset_count' => (int) $coverage['global_count'],
					'source_inline_style_count'            => $inline_count,
					'source_linked_stylesheet_count'       => $linked_count,
				),
			);
		}

		return $diagnostics;
	}

	/**
	 * Count captured interaction states from the Data Liberation sidecar and
	 * diagnose members the imported representation omitted.
	 *
	 * Absence, an empty envelope, a legacy schema string, or malformed JSON are
	 * not errors: they yield a zero count and no diagnostic. Residual loss is
	 * counted once per omitted member: Blocks Engine per-member diagnostics win
	 * when present, otherwise the sidecar and materialized `core/tab-panel`
	 * counts are reconciled. Capture-side `click-failed` stays a gap. A
	 * selectable-set `no-dialog` probe disproved a shared region, so the static
	 * HTML already holds the content and it is not an unsupported loss. Other
	 * `no-dialog` outcomes remain capture gaps, distinct from importer-side
	 * unmaterialized captured members.
	 *
	 * @param array<string,mixed> $artifact Source website artifact.
	 * @param array<string,mixed> $plan     Canonical WordPress site plan.
	 * @return array{recorded_state_count:int,captured_state_count:int,unrepresented_member_count:int,status_counts:array<string,int>,diagnostics:array<int,array<string,mixed>>}
	 */
	public static function captured_interaction_inventory( array $artifact, array $plan = array() ): array {
		$empty = array(
			'recorded_state_count'       => 0,
			'captured_state_count'       => 0,
			'unrepresented_member_count' => 0,
			'status_counts'              => array(
				'captured'     => 0,
				'click-failed' => 0,
				'no-dialog'    => 0,
			),
			'diagnostics'                => array(),
		);

		$route_index    = self::interaction_route_index( $plan );
		$reported_paths = self::reported_interaction_candidate_paths( $plan );
		$by_path        = array();
		$payload        = self::interaction_states_payload( $artifact );
		if ( null !== $payload ) {
			foreach ( self::interaction_state_pages( $payload ) as $page ) {
				if ( ! is_array( $page ) ) {
					continue;
				}
				$source_path = self::interaction_source_path( $page, $route_index );
				$states      = isset( $page['states'] ) && is_array( $page['states'] ) ? $page['states'] : array();
				foreach ( $states as $state ) {
					if ( ! is_array( $state ) ) {
						continue;
					}
					if ( ! isset( $by_path[ $source_path ] ) ) {
						$by_path[ $source_path ] = self::empty_interaction_path_row();
					}
					$status = self::interaction_state_status( $state );
					++$by_path[ $source_path ]['recorded'];
					$by_path[ $source_path ]['status_counts'][ $status ] = (int) ( $by_path[ $source_path ]['status_counts'][ $status ] ?? 0 ) + 1;
					$kind = isset( $state['kind'] ) && is_scalar( $state['kind'] ) ? sanitize_key( (string) $state['kind'] ) : '';
					if ( '' !== $kind ) {
						$by_path[ $source_path ]['kind_counts'][ $kind ] = (int) ( $by_path[ $source_path ]['kind_counts'][ $kind ] ?? 0 ) + 1;
					}
					if ( 'captured' === $status ) {
						++$by_path[ $source_path ]['captured'];
						if ( 'selectable-set' === $kind ) {
							++$by_path[ $source_path ]['captured_selectable'];
						}
					} elseif ( self::interaction_state_is_capture_gap( $status, $kind ) ) {
						++$by_path[ $source_path ]['capture_gap'];
					}
				}
			}
		}

		foreach ( self::interaction_producer_omission_counts( $plan, $route_index ) as $source_path => $omission ) {
			if ( ! isset( $by_path[ $source_path ] ) ) {
				$by_path[ $source_path ] = self::empty_interaction_path_row();
			}
			$by_path[ $source_path ]['be_failed']    = $omission['failed'];
			$by_path[ $source_path ]['be_truncated'] = $omission['truncated'];
			if ( 0 === (int) $by_path[ $source_path ]['recorded'] ) {
				foreach ( $omission['status_counts'] as $status => $count ) {
					if ( ! is_string( $status ) || '' === $status || $count < 1 ) {
						continue;
					}
					$by_path[ $source_path ]['status_counts'][ $status ] = (int) ( $by_path[ $source_path ]['status_counts'][ $status ] ?? 0 ) + $count;
				}
			}
		}
		foreach ( self::interaction_tab_panel_counts( $plan ) as $source_path => $tab_panels ) {
			if ( ! isset( $by_path[ $source_path ] ) ) {
				$by_path[ $source_path ] = self::empty_interaction_path_row();
			}
			$by_path[ $source_path ]['tab_panels'] = $tab_panels;
		}

		if ( array() === $by_path ) {
			return $empty;
		}

		ksort( $by_path, SORT_STRING );

		$recorded      = 0;
		$captured      = 0;
		$status_counts = $empty['status_counts'];
		$diagnostics   = array();
		foreach ( $by_path as $source_path => $row ) {
			$recorded += $row['recorded'];
			$captured += $row['captured'];
			foreach ( $row['status_counts'] as $status => $count ) {
				$status_counts[ $status ] = (int) ( $status_counts[ $status ] ?? 0 ) + $count;
			}
			ksort( $row['status_counts'], SORT_STRING );
			ksort( $row['kind_counts'], SORT_STRING );

			$capture_gap          = $row['be_failed'] > 0 ? $row['be_failed'] : $row['capture_gap'];
			$other_unmaterialized = max( 0, $row['captured'] - $row['captured_selectable'] );
			if ( $row['tab_panels'] > 0 ) {
				$selectable_unmaterialized = $row['captured_selectable'] > 0
					? max( 0, $row['captured_selectable'] - $row['tab_panels'] )
					: $row['be_truncated'];
			} elseif ( $row['be_failed'] > 0 || $row['be_truncated'] > 0 ) {
				$selectable_unmaterialized = $row['be_truncated'];
			} elseif ( $row['captured_selectable'] > 0 ) {
				$selectable_unmaterialized = $row['captured_selectable'];
			} else {
				$selectable_unmaterialized = $row['captured'];
				$other_unmaterialized      = 0;
			}
			$importer_unmaterialized = $selectable_unmaterialized + $other_unmaterialized;

			if ( isset( $reported_paths[ $source_path ] ) ) {
				continue;
			}
			if ( $capture_gap > 0 ) {
				$diagnostics[] = self::interaction_candidate_diagnostic(
					$source_path,
					Static_Site_Importer_Report_Diagnostics::CAPTURED_INTERACTION_CAPTURE_GAP_REASON,
					sprintf(
						'Source path %1$s recorded %2$d capture-side interaction outcome(s) that did not produce region content.',
						$source_path,
						$capture_gap
					),
					0,
					$capture_gap,
					array(
						'status_counts'  => self::stable_interaction_status_counts( $row['status_counts'] ),
						'kind_counts'    => $row['kind_counts'],
						'omission_class' => 'capture_side',
					)
				);
			}
			if ( $importer_unmaterialized > 0 ) {
				$diagnostics[] = self::interaction_candidate_diagnostic(
					$source_path,
					Static_Site_Importer_Report_Diagnostics::CAPTURED_INTERACTION_UNMATERIALIZED_REASON,
					sprintf(
						'Source path %1$s captured %2$d interaction state(s) that conversion did not materialize.',
						$source_path,
						$importer_unmaterialized
					),
					$importer_unmaterialized,
					$importer_unmaterialized,
					array(
						'status_counts'  => self::stable_interaction_status_counts( $row['status_counts'] ),
						'kind_counts'    => $row['kind_counts'],
						'omission_class' => 'importer',
					)
				);
			}
		}

		ksort( $status_counts, SORT_STRING );

		$unrepresented = 0;
		foreach ( $diagnostics as $diagnostic ) {
			$unrepresented += max( 0, (int) ( $diagnostic['recorded_state_count'] ?? 0 ) );
		}

		return array(
			'recorded_state_count'       => $recorded,
			'captured_state_count'       => $captured,
			'unrepresented_member_count' => $unrepresented,
			'status_counts'              => $status_counts,
			'diagnostics'                => $diagnostics,
		);
	}

	/**
	 * Detect a concrete layout hazard in the materialized plan without claiming a
	 * browser comparison has occurred. A topology warning alone is reportable but
	 * acceptable; generated fixed height on that CSS-owned container is unsafe.
	 *
	 * @param array<string,mixed> $plan Canonical WordPress site plan.
	 * @return array<int,array<string,mixed>> Unsafe layout diagnostics.
	 */
	public static function unsafe_layout_constraint_diagnostics( array $plan ): array {
		$topology_selectors = array();
		foreach ( is_array( $plan['diagnostics'] ?? null ) ? $plan['diagnostics'] : array() as $diagnostic ) {
			if ( ! is_array( $diagnostic ) || 'author_layout_topology_changed' !== ( $diagnostic['code'] ?? '' ) || ! is_scalar( $diagnostic['source_path'] ?? null ) || ! is_string( $diagnostic['selector'] ?? null ) || '' === $diagnostic['selector'] ) {
				continue;
			}
			$topology_selectors[ (string) $diagnostic['source_path'] ][ $diagnostic['selector'] ] = true;
		}
		if ( empty( $topology_selectors ) || ! class_exists( 'DOMDocument' ) || ! class_exists( 'DOMXPath' ) ) {
			return array();
		}

		$fixed_heights = array();
		foreach ( is_array( $plan['assets'] ?? null ) ? $plan['assets'] : array() as $asset ) {
			if ( ! is_array( $asset ) || 'engine-support' !== ( $asset['source'] ?? '' ) || ! is_string( $asset['content'] ?? null ) ) {
				continue;
			}
			if ( preg_match_all( '/\.([A-Za-z0-9_-]+)\{[^}]*\bheight\s*:\s*([1-9][0-9]*)px\s*!important/i', $asset['content'], $matches, PREG_SET_ORDER ) ) {
				foreach ( $matches as $match ) {
					$fixed_heights[ $match[1] ] = (int) $match[2];
				}
			}
		}
		if ( empty( $fixed_heights ) ) {
			return array();
		}

		$diagnostics = array();
		foreach ( is_array( $plan['pages'] ?? null ) ? $plan['pages'] : array() as $page ) {
			if ( ! is_array( $page ) || ! isset( $topology_selectors[ $page['source_path'] ?? '' ] ) ) {
				continue;
			}
			$markup = (string) ( $page['resolved_block_markup'] ?? $page['canonical_block_markup'] ?? '' );
			foreach ( array_keys( $topology_selectors[ (string) $page['source_path'] ] ) as $selector ) {
				foreach ( self::topology_selector_elements( $markup, $selector ) as $element ) {
					$classes = preg_split( '/\s+/', (string) $element->getAttribute( 'class' ) );
					$classes = is_array( $classes ) ? $classes : array();
					if ( ! in_array( 'blocks-engine-css-owned-layout', $classes, true ) ) {
						continue;
					}
					foreach ( $classes as $class ) {
						if ( ! isset( $fixed_heights[ $class ] ) ) {
							continue;
						}
						$diagnostics[] = array(
							'type'         => Static_Site_Importer_Report_Diagnostics::UNSAFE_LAYOUT_CONSTRAINT_TYPE,
							'code'         => Static_Site_Importer_Report_Diagnostics::UNSAFE_LAYOUT_CONSTRAINT_TYPE,
							'severity'     => 'error',
							'loss_class'   => Static_Site_Importer_Diagnostic_Loss_Classes::IMPORTER_MATERIALIZATION_BUG,
							'repair_class' => 'static-site-importer',
							'source_path'  => (string) $page['source_path'],
							'context'      => array(
								'class_name'      => $class,
								'fixed_height_px' => $fixed_heights[ $class ],
							),
							'message'      => sprintf( 'Generated layout support pins CSS-owned container .%1$s to %2$dpx after its direct-child topology changed. This fixed constraint can clip or collapse the materialized layout and is not safe to admit without a layout repair.', $class, $fixed_heights[ $class ] ),
						);
						unset( $fixed_heights[ $class ] );
					}
				}
			}
		}

		return $diagnostics;
	}

	/**
	 * Resolve the definite structural selector emitted by Blocks Engine topology
	 * evidence against the converted page markup. Page-level coincidence is not
	 * enough to prove that a fixed height constrains the changed container.
	 *
	 * @return array<int,DOMElement>
	 */
	public static function topology_selector_elements( string $markup, string $selector ): array {
		$segments = explode( ' > ', $selector );
		$xpath    = '';
		foreach ( $segments as $segment ) {
			if ( ! preg_match( '/^([a-z][a-z0-9-]*):nth-of-type\(([1-9][0-9]*)\)$/i', $segment, $match ) ) {
				return array();
			}
			$tag    = strtolower( $match[1] );
			$index  = (int) $match[2];
			$xpath .= ( '' === $xpath ? '/html/body/' : '/' ) . $tag . '[count(preceding-sibling::' . $tag . ')=' . ( $index - 1 ) . ']';
		}

		$document = new DOMDocument();
		$previous = libxml_use_internal_errors( true );
		$loaded   = $document->loadHTML( '<!DOCTYPE html><html><body>' . $markup . '</body></html>' );
		libxml_clear_errors();
		libxml_use_internal_errors( $previous );
		if ( ! $loaded ) {
			return array();
		}

		$nodes = ( new DOMXPath( $document ) )->query( $xpath );
		if ( false === $nodes ) {
			return array();
		}
		$elements = array();
		foreach ( $nodes as $element ) {
			if ( $element instanceof DOMElement ) {
				$elements[] = $element;
			}
		}

		return $elements;
	}

	/**
	 * Summarize author stylesheet coverage declared by plan asset scopes.
	 *
	 * @param array<int,mixed> $assets Plan assets.
	 * @return array{global_count:int,by_source_path:array<string,int>}
	 */
	public static function author_stylesheet_scope_coverage( array $assets ): array {
		$coverage = array(
			'global_count'   => 0,
			'by_source_path' => array(),
		);
		foreach ( $assets as $asset ) {
			if ( ! is_array( $asset ) || 'css' !== ( $asset['kind'] ?? '' ) ) {
				continue;
			}
			if ( 'editor' === ( $asset['stylesheet_target'] ?? 'both' ) ) {
				continue; // Editor-only styles never reach the imported frontend page.
			}
			if ( in_array( (string) ( $asset['source'] ?? '' ), self::ENGINE_STYLESHEET_SOURCES, true ) ) {
				continue;
			}
			// Valid plans declare scopes on every stylesheet asset; treat a missing
			// declaration as global so the gate cannot report a covered page.
			$scopes = isset( $asset['scopes'] ) && is_array( $asset['scopes'] ) ? $asset['scopes'] : array( array( 'kind' => 'global' ) );
			foreach ( $scopes as $scope ) {
				if ( ! is_array( $scope ) ) {
					continue;
				}
				if ( 'global' === ( $scope['kind'] ?? '' ) ) {
					++$coverage['global_count'];
					continue;
				}
				$scope_source = isset( $scope['source_path'] ) && is_scalar( $scope['source_path'] ) ? (string) $scope['source_path'] : '';
				if ( '' !== $scope_source ) {
					$coverage['by_source_path'][ $scope_source ] = (int) ( $coverage['by_source_path'][ $scope_source ] ?? 0 ) + 1;
				}
			}
		}

		return $coverage;
	}

	/**
	 * Index artifact file contents by path for source-evidence checks.
	 *
	 * Supports both canonical list-form files ({path, content|content_base64})
	 * and compiler map-form files (path => content). Files whose payload is not
	 * inline (e.g. payload references) contribute no evidence.
	 *
	 * @param array<string,mixed> $artifact Source website artifact.
	 * @return array<string,string> Contents keyed by artifact path.
	 */
	public static function artifact_file_contents( array $artifact ): array {
		$files    = isset( $artifact['files'] ) && is_array( $artifact['files'] ) ? $artifact['files'] : array();
		$contents = array();
		foreach ( $files as $key => $file ) {
			if ( is_string( $key ) && is_string( $file ) ) {
				$contents[ $key ] = $file;
				continue;
			}
			if ( ! is_array( $file ) || ! is_scalar( $file['path'] ?? null ) ) {
				continue;
			}
			$path = (string) $file['path'];
			if ( isset( $file['content'] ) && is_string( $file['content'] ) ) {
				$contents[ $path ] = $file['content'];
				continue;
			}
			if ( isset( $file['content_base64'] ) && is_string( $file['content_base64'] ) ) {
				$decoded = base64_decode( $file['content_base64'], true ); // phpcs:ignore WordPress.PHP.DiscouragedPHPFunctions.obfuscation_base64_decode -- Decodes declared artifact transport encoding.
				if ( false !== $decoded ) {
					$contents[ $path ] = $decoded;
				}
			}
		}

		return $contents;
	}

	/**
	 * Decode the captured-interactions sidecar from artifact files.
	 *
	 * @param array<string,mixed> $artifact Source website artifact.
	 * @return array<string,mixed>|null
	 */
	private static function interaction_states_payload( array $artifact ): ?array {
		$files = self::artifact_file_contents( $artifact );
		$paths = array_keys( $files );
		sort( $paths, SORT_STRING );
		$chosen = '';
		foreach ( $paths as $path ) {
			$normalized = str_replace( '\\', '/', (string) $path );
			$base       = basename( $normalized );
			if ( 'interaction-states.json' === $base ) {
				$chosen = $path;
				break;
			}
		}
		if ( '' === $chosen || ! isset( $files[ $chosen ] ) ) {
			return null;
		}
		$raw = trim( (string) $files[ $chosen ] );
		if ( '' === $raw ) {
			return null;
		}
		$decoded = json_decode( $raw, true );

		return is_array( $decoded ) ? $decoded : null;
	}

	/**
	 * Normalize envelope, legacy page, or list-shaped captured-interaction payloads.
	 *
	 * @param array<array-key,mixed> $payload Decoded sidecar.
	 * @return array<int,mixed>
	 */
	private static function interaction_state_pages( array $payload ): array {
		if ( isset( $payload['pages'] ) && is_array( $payload['pages'] ) ) {
			return array_values( $payload['pages'] );
		}
		if ( isset( $payload['states'] ) && is_array( $payload['states'] ) ) {
			return array( $payload );
		}
		if ( array_is_list( $payload ) ) {
			return $payload;
		}

		return array();
	}

