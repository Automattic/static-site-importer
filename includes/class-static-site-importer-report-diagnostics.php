	/**
	 * Normalize partial report quality and retain unresolved compiler fallbacks.
	 *
	 * Website-artifact composition supplies the compiler's nested metrics rather
	 * than the complete conversion-report quality shape. Preserve every supplied
	 * report value while making the quality gate consume its authoritative fallback
	 * count until a materialization receipt explicitly resolves it.
	 *
	 * @param Static_Site_Importer_Import_Report $report Import report.
	 * @return void
	 */
	private static function normalize_quality_report( Static_Site_Importer_Import_Report $report ): void {
		$supplied = isset( $report['quality'] ) && is_array( $report['quality'] ) ? $report['quality'] : array();
		$metrics  = isset( $supplied['metrics'] ) && is_array( $supplied['metrics'] ) ? $supplied['metrics'] : array();
		$quality  = array_merge( self::quality_defaults(), $metrics, $supplied );

		$plan_quality = isset( $report['blocks_engine']['wordpress_site_plan']['quality'] ) && is_array( $report['blocks_engine']['wordpress_site_plan']['quality'] )
			? $report['blocks_engine']['wordpress_site_plan']['quality']
			: array();
		$plan_metrics = isset( $plan_quality['metrics'] ) && is_array( $plan_quality['metrics'] ) ? $plan_quality['metrics'] : $plan_quality;
		if ( isset( $plan_metrics['fallback_count'] ) && is_numeric( $plan_metrics['fallback_count'] ) ) {
			$quality['fallback_count'] = max( (int) $quality['fallback_count'], (int) $plan_metrics['fallback_count'] );
		}

		$report['quality'] = $quality;
	}

	/**
	 * Split compiler fallbacks into fail-closed unsupported loss and explicitly
	 * accepted, bounded runtime preservation. A count without matching evidence
	 * remains unsupported so producers cannot weaken the admission gate by label.
	 *
	 * @param array<int,mixed> $diagnostics Normalized diagnostics.
	 * @param int              $fallback_count Compiler fallback count.
	 * @return array{accepted:int,unsupported:int}
	 */
	private static function fallback_admission_counts( array $diagnostics, int $fallback_count ): array {
		$accepted = 0;
		foreach ( $diagnostics as $diagnostic ) {
			if ( is_array( $diagnostic ) && self::is_accepted_preserved_runtime_island( $diagnostic ) ) {
				++$accepted;
			}
		}

		$accepted = min( max( 0, $fallback_count ), $accepted );
		return array(
			'accepted'    => $accepted,
			'unsupported' => max( 0, $fallback_count - $accepted ),
		);
	}

	/**
	 * Require a complete generic runtime-preservation contract before admitting a
	 * fallback. Raw HTML and unsafe or unbounded payloads always remain gated.
	 *
	 * @param array<string,mixed> $diagnostic Normalized diagnostic.
	 */
	private static function is_accepted_preserved_runtime_island( array $diagnostic ): bool {
		if ( 'unsupported_html_fallback' !== ( $diagnostic['type'] ?? '' ) ) {
			return false;
		}
		if ( ! in_array( $diagnostic['loss_class'] ?? '', array( 'runtime_island_preserved', 'preserved_runtime_island' ), true ) || ! in_array( $diagnostic['acceptability'] ?? '', array( 'acceptable_conversion', 'acceptable_preservation' ), true ) ) {
			return false;
		}
		if ( 'sanitized_embed_markup' !== ( $diagnostic['preservation_strategy'] ?? '' ) || '' === trim( (string) ( $diagnostic['runtime_requirement'] ?? '' ) ) || '' === trim( (string) ( $diagnostic['materialization_path'] ?? '' ) ) ) {
			return false;
		}
		if ( '' === trim( (string) ( $diagnostic['id'] ?? '' ) ) || '' === trim( (string) ( $diagnostic['source_path'] ?? '' ) ) || '' === trim( (string) ( $diagnostic['selector'] ?? '' ) ) || '' === trim( (string) ( $diagnostic['reason_code'] ?? '' ) ) ) {
			return false;
		}

		$payload = (string) ( $diagnostic['source_html_preview'] ?? $diagnostic['html_excerpt'] ?? '' );
		if ( '' === trim( $payload ) || strlen( $payload ) > 8192 ) {
			return false;
		}

		return 1 !== preg_match( '/<\s*(?:script|style)\b|\bon[a-z]+\s*=|(?:javascript|data)\s*:|\bsrcdoc\s*=|<!--\s*wp:(?:html|freeform)\b/i', $payload )
			&& ! in_array( $diagnostic['block_name'] ?? '', array( 'core/html', 'core/freeform' ), true );
	}

	/**
	 * Record a generated companion-plugin dependency into a conversion report.
	 *
	 * Mirrors the WooCommerce/Jetpack directory-dependency surface so the gate and
	 * diagnostics treat a generated companion as a first-class declared dependency:
	 * a present companion emits an info diagnostic, a waived-but-missing one emits a
	 * warning, and a required-but-missing one increments the dependency-failure
	 * quality counter (which fails the import) and emits an error diagnostic. The
	 * declared dependency row is stored under `companion_plugins.dependencies` keyed
	 * by the namespaced companion slug, distinct from `commerce.dependencies`.
	 *
	 * @param Static_Site_Importer_Import_Report $report     Conversion report (mutated in place).
	 * @param array<string, mixed> $dependency Companion dependency definition.
	 * @param bool                 $waived     Whether enforcement is waived.
	 * @return void
	 */
	public static function record_companion_plugin_dependency( Static_Site_Importer_Import_Report $report, array $dependency, bool $waived ): void {
		$row  = Static_Site_Importer_Entity_Materializer_Registry::companion_dependency_row( $dependency, $waived );
		$slug = (string) ( $row['slug'] ?? '' );
		if ( '' === $slug ) {
			return;
		}

		$companion = $report->section( 'companion_plugins' );
		if ( ! isset( $companion['dependencies'] ) || ! is_array( $companion['dependencies'] ) ) {
			$companion['dependencies'] = array();
		}
		$companion['dependencies'][ $slug ] = $row;
		$report->set_section( 'companion_plugins', $companion );

		$source = 'companion_plugins.dependencies.' . $slug;

		if ( ! empty( $row['active'] ) ) {
			$island_handles  = isset( $row['island_handles'] ) && is_array( $row['island_handles'] ) ? $row['island_handles'] : array();
			$runtime_scripts = isset( $row['runtime_scripts'] ) && is_array( $row['runtime_scripts'] ) ? $row['runtime_scripts'] : array();
			self::mark_companion_script_fallbacks_materialized( $report, $runtime_scripts, $slug );
			$present = array(
				'code'           => 'companion_plugin_present',
				'severity'       => 'info',
				'source'         => $source,
				'message'        => sprintf( 'Companion plugin %s is active; generated blocks are available theme-independently.', $slug ),
				'slug'           => $slug,
				'block_names'    => $row['block_names'] ?? array(),
				'island_handles' => $island_handles,
			);
			// Preserved island JS that rides the active companion plugin is
			// carried theme-independently; flag the runtime-carried signal the
			// honest gate looks for so this JS is not counted as lost.
			if ( ! empty( $island_handles ) ) {
				$present['runtime_carried'] = true;
				$present['message']         = sprintf( 'Companion plugin %s is active; generated blocks and preserved island JS are carried theme-independently.', $slug );
			}
			$report->append_diagnostic( $present );
			return;
		}

		if ( $waived ) {
			$report->append_diagnostic(
				array(
					'code'        => 'companion_plugin_waived',
					'severity'    => 'warning',
					'source'      => $source,
					'message'     => sprintf( 'Companion plugin %s requirement was waived; generated blocks were not installed.', $slug ),
					'slug'        => $slug,
					'block_names' => $row['block_names'] ?? array(),
				)
			);
			return;
		}

		$report->increment_quality( 'companion_plugin_dependency_failures' );
		$report->append_diagnostic(
			array(
				'code'        => 'companion_plugin_missing',
				'severity'    => 'error',
				'source'      => $source,
				'message'     => sprintf( 'Companion plugin %s is required to house generated blocks but is not installed/active.', $slug ),
				'slug'        => $slug,
				'block_names' => $row['block_names'] ?? array(),
			)
		);
	}

	/**
	 * Build the compact report summary consumed by validation harnesses.
	 *
	 * @param array<string,mixed>|Static_Site_Importer_Import_Report $report  Full conversion report.
	 * @param array<string, mixed> $quality Finalized quality summary.
	 * @return array<string, mixed>
	 */
	public static function import_report_summary( array|Static_Site_Importer_Import_Report $report, array $quality ): array {
		$diagnostics            = isset( $report['diagnostics'] ) && is_array( $report['diagnostics'] ) ? $report['diagnostics'] : array();
