	/**
	 * Build the finding packet artifact set for repair-loop routing.
	 *
	 * @param array<string,mixed>|Static_Site_Importer_Import_Report $report Full import report.
	 * @return array<string,mixed>
	 */
	public static function finding_packets( array|Static_Site_Importer_Import_Report $report ): array {
		$diagnostics = isset( $report['diagnostics'] ) && is_array( $report['diagnostics'] ) ? $report['diagnostics'] : array();
		$packets     = array();

		foreach ( $diagnostics as $diagnostic ) {
			if ( ! is_array( $diagnostic ) || ! self::diagnostic_is_finding_packet_candidate( $diagnostic ) ) {
				continue;
			}

			$packets[] = self::finding_packet_from_diagnostic( $diagnostic, $report );
		}

		return array(
			'schema'        => 'blocks-engine/finding-packets/v1',
			'artifact_type' => 'FindingPacketSet',
			'version'       => 1,
			'status'        => empty( $packets ) ? 'clean' : 'reported',
			'count'         => count( $packets ),
			'packets'       => $packets,
		);
	}

	/**
	 * Detect page routes that materialize without any author stylesheet asset
	 * while their source document demonstrably ships author styles.
	 *
	 * The importer is the only layer that sees both the canonical plan's
	 * asset-to-route scopes and the source artifact, so it owns reporting the
	 * "page ships without its styles while the import reports clean" failure
	 * class (Automattic/blocks-engine#1241) regardless of which upstream stage
	 * regresses next. A page counts as covered when any non-engine stylesheet
	 * asset (coalesced `stylesheet-bundle-*`, uncoalesced `source-author-*`, or
	 * a copied author CSS file) is scoped to its route or declared global;
	 * `engine-support` and `editor-static-state` assets are engine-generated
	 * and never satisfy author coverage. Source evidence requires a non-empty
	 * inline `<style>` payload or a linked stylesheet that resolves to a
	 * non-empty artifact-local CSS file, so a warning always means author CSS
	 * the pipeline had in hand was dropped.
	 *
	 * @param array<string,mixed> $plan     Canonical WordPress site plan.
	 * @param array<string,mixed> $artifact Source website artifact.
	 * @return array<int,array<string,mixed>> Warning diagnostics, one per uncovered route.
	 */
	public static function missing_author_stylesheet_diagnostics( array $plan, array $artifact ): array {
		$pages = isset( $plan['pages'] ) && is_array( $plan['pages'] ) ? $plan['pages'] : array();
		if ( array() === $pages ) {
			return array();
		}

		$coverage = self::author_stylesheet_scope_coverage( isset( $plan['assets'] ) && is_array( $plan['assets'] ) ? $plan['assets'] : array() );
		$files    = self::artifact_file_contents( $artifact );

		$diagnostics = array();
		foreach ( $pages as $page ) {
			if ( ! is_array( $page ) || ! is_scalar( $page['source_path'] ?? null ) ) {
				continue;
			}
			$source_path  = (string) $page['source_path'];
			$scoped_count = (int) ( $coverage['by_source_path'][ $source_path ] ?? 0 );
			if ( $scoped_count > 0 || $coverage['global_count'] > 0 ) {
				continue;
			}
			$html = $files[ $source_path ] ?? '';
			if ( '' === $html ) {
				continue; // Without source content there is no proof author styles were lost.
			}
			$inline_count = self::nonempty_inline_style_count( $html );
			$linked_count = self::linked_local_stylesheet_count( $html, $source_path, $files );
			if ( 0 === $inline_count && 0 === $linked_count ) {
				continue;
			}
			$route         = (string) ( $page['route']['path'] ?? '' );
			$route_path    = trim( $route, '/' );
			$diagnostics[] = array(
				'type'        => self::PAGE_WITHOUT_AUTHOR_STYLES_TYPE,
				'code'        => self::PAGE_WITHOUT_AUTHOR_STYLES_TYPE,
				'severity'    => 'warning',
				'source'      => $source_path,
				'source_path' => $source_path,
				'route_path'  => $route_path,
				'front_page'  => '/' === $route,
				'message'     => sprintf(
					'Page %1$s (route "/%2$s") materialized without any author stylesheet asset scoped to its route while its source document contains author styles (%3$d inline style block(s), %4$d linked local stylesheet(s)). The imported page will render without its source styling.',
					$source_path,
					$route_path,
					$inline_count,
					$linked_count
				),
				'reason_code' => 'no_author_scoped_stylesheet_assets',
				'stage'       => 'materialization',
				'loss_class'  => Static_Site_Importer_Diagnostic_Loss_Classes::IMPORTER_MATERIALIZATION_BUG,
				'context'     => array(
					'source_path'                          => $source_path,
					'route_path'                           => $route_path,
					'author_scoped_stylesheet_asset_count' => $scoped_count,
					'global_author_stylesheet_asset_count' => (int) $coverage['global_count'],
					'source_inline_style_count'            => $inline_count,
					'source_linked_stylesheet_count'       => $linked_count,
				),
			);
		}

		return $diagnostics;
	}

	/**
	 * Summarize author stylesheet coverage declared by plan asset scopes.
	 *
	 * @param array<int,mixed> $assets Plan assets.
	 * @return array{global_count:int,by_source_path:array<string,int>}
	 */
	private static function author_stylesheet_scope_coverage( array $assets ): array {
		$coverage = array(
			'global_count'   => 0,
			'by_source_path' => array(),
		);
		foreach ( $assets as $asset ) {
			if ( ! is_array( $asset ) || 'css' !== ( $asset['kind'] ?? '' ) ) {
				continue;
			}
			if ( 'editor' === ( $asset['stylesheet_target'] ?? 'both' ) ) {
				continue; // Editor-only styles never reach the imported frontend page.
			}
			if ( in_array( (string) ( $asset['source'] ?? '' ), self::ENGINE_STYLESHEET_SOURCES, true ) ) {
				continue;
			}
			// Valid plans declare scopes on every stylesheet asset; treat a missing
			// declaration as global so the gate cannot report a covered page.
			$scopes = isset( $asset['scopes'] ) && is_array( $asset['scopes'] ) ? $asset['scopes'] : array( array( 'kind' => 'global' ) );
			foreach ( $scopes as $scope ) {
				if ( ! is_array( $scope ) ) {
					continue;
				}
				if ( 'global' === ( $scope['kind'] ?? '' ) ) {
					++$coverage['global_count'];
					continue;
				}
				$scope_source = isset( $scope['source_path'] ) && is_scalar( $scope['source_path'] ) ? (string) $scope['source_path'] : '';
				if ( '' !== $scope_source ) {
					$coverage['by_source_path'][ $scope_source ] = (int) ( $coverage['by_source_path'][ $scope_source ] ?? 0 ) + 1;
				}
			}
		}

		return $coverage;
	}

	/**
	 * Index artifact file contents by path for source-evidence checks.
	 *
	 * Supports both canonical list-form files ({path, content|content_base64})
	 * and compiler map-form files (path => content). Files whose payload is not
	 * inline (e.g. payload references) contribute no evidence.
	 *
	 * @param array<string,mixed> $artifact Source website artifact.
	 * @return array<string,string> Contents keyed by artifact path.
	 */
	private static function artifact_file_contents( array $artifact ): array {
		$files    = isset( $artifact['files'] ) && is_array( $artifact['files'] ) ? $artifact['files'] : array();
		$contents = array();
		foreach ( $files as $key => $file ) {
			if ( is_string( $key ) && is_string( $file ) ) {
				$contents[ $key ] = $file;
				continue;
			}
			if ( ! is_array( $file ) || ! is_scalar( $file['path'] ?? null ) ) {
				continue;
			}
			$path = (string) $file['path'];
			if ( isset( $file['content'] ) && is_string( $file['content'] ) ) {
				$contents[ $path ] = $file['content'];
				continue;
			}
			if ( isset( $file['content_base64'] ) && is_string( $file['content_base64'] ) ) {
				$decoded = base64_decode( $file['content_base64'], true ); // phpcs:ignore WordPress.PHP.DiscouragedPHPFunctions.obfuscation_base64_decode -- Decodes declared artifact transport encoding.
				if ( false !== $decoded ) {
					$contents[ $path ] = $decoded;
				}
			}
		}

		return $contents;
	}

	/**
	 * Count non-empty inline `<style>` payloads with linear string scanning.
	 *
	 * Deliberately avoids regular expressions over the document: a lazy
	 * multi-megabyte `<style>(.*?)</style>` scan exhausting the PCRE backtrack
	 * limit is exactly the upstream failure this diagnostic exists to catch.
	 *
	 * @param string $html Source document HTML.
	 * @return int
	 */
	private static function nonempty_inline_style_count( string $html ): int {
		$count  = 0;
		$offset = 0;
		$length = strlen( $html );
		while ( $offset < $length ) {
			$open = stripos( $html, '<style', $offset );
			if ( false === $open ) {
				break;
			}
			$boundary = $html[ $open + 6 ] ?? '';
			if ( '>' !== $boundary && '/' !== $boundary && '' !== trim( $boundary ) ) {
				$offset = $open + 6;
				continue;
			}
			$tag_end = strpos( $html, '>', $open );
			if ( false === $tag_end ) {
				break;
			}
			$close  = stripos( $html, '</style', $tag_end + 1 );
			$offset = false === $close ? $tag_end + 1 : $close + 8;
			if ( false === $close ) {
				continue;
			}
			$attributes = substr( $html, $open + 6, $tag_end - $open - 6 );
			if ( false !== stripos( $attributes, 'type' ) && false === stripos( $attributes, 'css' ) ) {
				continue; // Non-CSS style payloads are not author stylesheets.
			}
			if ( '' !== trim( substr( $html, $tag_end + 1, $close - $tag_end - 1 ) ) ) {
				++$count;
			}
		}

		return $count;
	}

	/**
	 * Count linked stylesheets that resolve to non-empty artifact-local CSS files.
	 *
	 * @param string               $html        Source document HTML.
	 * @param string               $source_path Artifact path of the source document.
	 * @param array<string,string> $files       Artifact contents keyed by path.
	 * @return int
	 */
	private static function linked_local_stylesheet_count( string $html, string $source_path, array $files ): int {
		$count  = 0;
		$offset = 0;
		$length = strlen( $html );
		while ( $offset < $length ) {
			$open = stripos( $html, '<link', $offset );
			if ( false === $open ) {
				break;
			}
			$tag_end = strpos( $html, '>', $open );
			if ( false === $tag_end ) {
				break;
			}
			$offset = $tag_end + 1;
			$tag    = substr( $html, $open, $tag_end - $open + 1 );
			if ( false === stripos( $tag, 'stylesheet' ) ) {
				continue;
			}
			$href = self::tag_attribute( $tag, 'href' );
			$href = explode( '#', explode( '?', $href, 2 )[0], 2 )[0];
			if ( '' === $href || preg_match( '#^(?:[a-z][a-z0-9+.-]*:|//)#i', $href ) ) {
				continue; // Remote or scheme-qualified stylesheets are not artifact-local author CSS.
			}
			$resolved = self::artifact_relative_path( $source_path, $href );
			if ( '' !== $resolved && '' !== trim( (string) ( $files[ $resolved ] ?? '' ) ) ) {
				++$count;
			}
		}

		return $count;
	}

	/**
	 * Extract one attribute value from an already-bounded tag substring.
	 *
	 * The regex only ever runs against a single extracted tag, never a document.
	 *
	 * @param string $tag       Complete tag substring.
	 * @param string $attribute Attribute name.
	 * @return string
	 */
	private static function tag_attribute( string $tag, string $attribute ): string {
		if ( ! preg_match( '/(?<![\w-])' . preg_quote( $attribute, '/' ) . '\s*=\s*(?:"([^"]*)"|\'([^\']*)\'|([^\s"\'>]+))/i', $tag, $matches ) ) {
			return '';
		}
		foreach ( array( 1, 2, 3 ) as $group ) {
			if ( isset( $matches[ $group ] ) && '' !== $matches[ $group ] ) {
				return trim( $matches[ $group ] );
			}
		}

		return '';
	}

	/**
	 * Resolve a document-relative reference to an artifact-root-relative path.
	 *
	 * @param string $source_path Artifact path of the referencing document.
	 * @param string $reference   Raw href reference.
	 * @return string
	 */
	private static function artifact_relative_path( string $source_path, string $reference ): string {
		$reference = str_replace( '\\', '/', trim( $reference ) );
		$segments  = array();
		if ( ! str_starts_with( $reference, '/' ) ) {
			foreach ( explode( '/', str_replace( '\\', '/', dirname( $source_path ) ) ) as $segment ) {
				if ( '' !== $segment && '.' !== $segment ) {
					$segments[] = $segment;
				}
			}
		}
		foreach ( explode( '/', ltrim( $reference, '/' ) ) as $segment ) {
			if ( '' === $segment || '.' === $segment ) {
				continue;
			}
			if ( '..' === $segment ) {
				array_pop( $segments );
				continue;
			}
			$segments[] = $segment;
		}

		return implode( '/', $segments );
	}

	/**
	 * Finalize quality summary and gate status.
	 *
	 * @param Static_Site_Importer_Import_Report $report Import report.
	 * @param array<string,mixed> $args   Import args.
	 * @return array<string, mixed>
	 */
	public static function finalize_quality_report( Static_Site_Importer_Import_Report $report, array $args ): array {
		self::normalize_quality_report( $report );
		self::reconcile_provider_materialized_fallbacks( $report );
		self::mark_active_companion_script_fallbacks_materialized( $report );
		self::normalize_import_diagnostics( $report );

		$quality            = $report['quality'];
		$fallback_admission = self::fallback_admission_counts( $report['diagnostics'] ?? array(), (int) $quality['fallback_count'] );
		$quality['accepted_preserved_runtime_island_count'] = $fallback_admission['accepted'];
		$quality['unsupported_fallback_count']              = $fallback_admission['unsupported'];
		$reasons = array();
		if ( $quality['unsupported_fallback_count'] > 0 ) {
			$reasons[] = 'unsupported_html_fallback';
		}
		if ( $quality['content_loss_count'] > 0 ) {
			$reasons[] = 'content_loss_abort';
		}
		if ( $quality['empty_conversion_count'] > 0 ) {
			$reasons[] = 'empty_conversion';
		}
		if ( $quality['core_html_block_count'] > 0 ) {
			$reasons[] = 'core_html_block';
		}
		if ( $quality['freeform_block_count'] > 0 ) {
			$reasons[] = 'freeform_block';
		}
		if ( $quality['invalid_block_count'] > 0 ) {
			$reasons[] = 'invalid_block';
		}
		if ( $quality['unsafe_svg_count'] > 0 ) {
			$reasons[] = 'unsafe_inline_svg';
		}
		if ( $quality['svg_materialization_failure_count'] > 0 ) {
			$reasons[] = 'svg_materialization_failure';
		}
		if ( $quality['svg_sprite_reference_failure_count'] > 0 ) {
			$reasons[] = 'svg_sprite_reference_failure';
		}
		if ( ( $quality['commerce_dependency_failures'] ?? 0 ) > 0 ) {
			$reasons[] = 'woocommerce_missing';
		}
		if ( ( $quality['companion_plugin_dependency_failures'] ?? 0 ) > 0 ) {
			$reasons[] = 'companion_plugin_missing';
		}
		if ( ( $quality['runtime_dependency_parity_issue_count'] ?? 0 ) > 0 ) {
			$reasons[] = 'runtime_dependency_parity';
		}
		if ( ( $quality['semantic_parity_failure_count'] ?? 0 ) > 0 ) {
			$reasons[] = 'semantic_parity_failure';
		}

		$quality['pass']            = empty( $reasons );
		$quality['failure_reasons'] = $reasons;
		$quality['fail_import']     = false;
		if ( ! empty( $args['fail_on_quality'] ) && ! $quality['pass'] ) {
			$quality['fail_import'] = true;
		}
		if ( array_key_exists( 'max_fallbacks', $args ) && null !== $args['max_fallbacks'] && $quality['unsupported_fallback_count'] > (int) $args['max_fallbacks'] ) {
			$quality['fail_import'] = true;
		}
		if ( in_array( 'woocommerce_missing', $reasons, true ) ) {
			$quality['fail_import'] = true;
		}
		if ( in_array( 'companion_plugin_missing', $reasons, true ) ) {
			$quality['fail_import'] = true;
		}

		$quality['diagnostic_refs'] = self::quality_diagnostic_refs( $report['diagnostics'] ?? array() );
		$report['quality']          = $quality;
		self::normalize_source_document_diagnostic_refs( $report );
		$report['artifact_diagnostics'] = Static_Site_Importer_Artifact_Diagnostics_Adapter::build_for_import_report( $report );

		return $quality;
	}

